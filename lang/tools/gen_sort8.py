NETWORK = [(0, 2), (1, 3), (4, 6), (5, 7), (0, 4), (1, 5), (2, 6), (3, 7), (0, 1), (2, 3), (4, 5), (6, 7),
           (2, 4), (3, 5), (1, 4), (3, 6), (1, 2), (3, 4), (5, 6)]
# the first byte of the eight colours in examples/demos/sort.s: it alone decides their order (and the one tie), so this sorts the same way
INPUT = [0xb0, 0x30, 0x70, 0x20, 0xf0, 0x30, 0xc0, 0x10]

out = []
def numlist(label):
    items = ", \" \", ".join("a[%d]" % k for k in range(8))
    return '  print "%s", %s, "\\n";' % (label, items)

out.append("""// Sort eight numbers reversibly with a sorting network, written in rev (generated by lang/tools/gen_sort8.py).
// The same network as examples/demos/sort.s (19 compare-exchanges) on the same eight numbers in the same order (there they are the red
// byte of eight colours, here just the numbers), so the compiler's output can be compared with the hand-written assembly: see lang/README.md.
// Each compare-exchange swaps if the pair is out of order, and files one bit in `garbage`: that bit is what the sort forgot.
// Sorted list + garbage = the original list, so the program run backwards unsorts it exactly.
// It prints the list before and after, and the 19 flags (1 = that pair was swapped): step back and the text un-prints.
var f = 0;
var a[8] = {%s};
var garbage[19];
out a;

main {""" % ", ".join(str(x) for x in INPUT))
out.append(numlist("before: "))
for k, (i, j) in enumerate(NETWORK):
    out.append("  if (a[%d] > a[%d]) { a[%d] <=> a[%d]; f += 1; } fi (f != 0);" % (i, j, i, j))
    out.append("  garbage[%d] ^= f; f ^= garbage[%d];" % (k, k))
out.append(numlist("sorted: "))
out.append('  print "flags:  ", %s, "\\n";' % ", ".join("garbage[%d]" % k for k in range(19)))
out.append("}")
import os
target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "examples", "rev", "sort8.rev")
open(target, "w", newline="\n").write("\n".join(out) + "\n")
print("ok")
