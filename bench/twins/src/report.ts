// Produces bench/TWINS.md: the fair comparison (SPEC section 12). Run: npm run report (in bench/twins).
import { writeFileSync } from 'node:fs';

import { Checkpoints } from './baselines.js';
import type { Conv } from './conv.js';
import { runPong, runSort } from './scenario.js';

const f0 = (x: number): string => Math.round(x).toLocaleString('en-GB');
const f1 = (x: number): string => x.toFixed(1);
const out: string[] = [];
const line = (s = ''): number => out.push(s);

/** Mean and worst replay steps to seek to `samples` evenly spread earlier times, using the real checkpoint structure. */
function seekCost(m: Conv, cp: Checkpoints, samples = 200): { mean: number; worst: number } {
  const T = m.t;
  let sum = 0;
  let worst = 0;
  for (let i = 0; i < samples; i++) {
    const t = Math.floor((T * (i + 0.5)) / samples);
    const r = cp.seek(m, t);
    sum += r;
    worst = Math.max(worst, r);
  }
  cp.seek(m, T);
  return { mean: sum / samples, worst };
}

const SORT_KS = [5, 25, 100]; // the whole sort is about 100 steps, so the intervals are small
const sort = await runSort(undefined, SORT_KS);
const SEED = sort.conv.stats;
line('# Fair baselines: conventional twins vs the reversible programs');
line();
line('Generated by `npm run report` in `bench/twins` (about 20 seconds). Definitions: `spec/SPEC.md` section 12. Every');
line('number below is measured, not estimated; the tests in `bench/twins/test` check that each twin draws the same picture as');
line('the reversible program on the real engines, and that the tight diary and the checkpoints rewind **exactly**.');
line();
line('## What is being compared');
line('- **Reversible**: `examples/demos/sort.s` and `examples/demos/pong.s` on the reversible engine. No history in the machine; the program');
line('  keeps its own garbage.');
line('- **Conventional twin**: the same job written for an ordinary overwriting machine (`bench/twins/src/twins.ts`, run by a');
line('  small conventional machine in `src/conv.ts` with the same memory map and input window). Same network, same game, same');
line('  pixels. Nothing is stored for undo by the program itself.');
line('- **Naive diary**: our logging VM on the *reversible* program (48 bytes a step; measured).');
line('- **Tight diary**: a real bit-packed history for the *conventional* twin: per overwriting step the old value\'s significant');
line('  bits plus a 6-bit length, per join the index of the predecessor. It rewinds exactly (tested). This is the strongest');
line('  simple diary we know how to write; a cleverer compressing one could be smaller.');
line('- **Full-width diary**: 32 bits per overwriting step, the worst-case count `bits_erased` of SPEC 12.2.');
line('- **Checkpoint and replay**: a snapshot every K steps (registers plus every word the program ever writes); to go back,');
line('  restore the nearest earlier snapshot and run forward.');
line();

// ---- sort ----
const sortTightB = sort.conv.stack.byteSize;
line('## Sort (8 numbers, 19-comparator network)');
line();
line('| | reversible | conventional twin |');
line('|---|---|---|');
line(`| instructions executed | ${f0(sort.revSteps)} | ${f0(SEED.steps)} |`);
line(`| code size (instructions) | ${sort.revCodeLength} | ${sort.convCodeLength} |`);
line(`| overwriting steps | 0 | ${f0(SEED.destroyingSteps)} |`);
line(`| join bits | 0 | ${f0(SEED.joinBits)} |`);
line(`| **bits erased** (worst case, SPEC 12.2) | 0 | ${f0(SEED.bitsErased)} |`);
line(`| program garbage kept | ${sort.garbageFlags} flag(s) set of 19 (at most 19 bits) | 0 |`);
line(`| naive diary (logging VM, 48 B/step) | ${f0(sort.historyNaive)} B | n/a |`);
line(`| full-width diary | n/a | ${f0(SEED.bitsErased / 8)} B |`);
line(`| **tight diary** (real, rewinds exactly) | n/a | **${f0(sortTightB)} B** |`);
line(`| machine history, reversible engine | **0 B** | n/a |`);
line();
line(`Step overhead of reversibility on this program: **${f1(sort.revSteps / SEED.steps)}x** instructions, **${f1(sort.revCodeLength / sort.convCodeLength)}x** code.`);
line(`The information floor for sorting 8 distinct numbers is log2(8!) = 15.3 bits; the reversible sort keeps at most 19 bits`);
line(`(one per comparator, ${sort.garbageFlags} set this time), so it sits within a few bits of the floor. The tight diary keeps`);
line(`${f0(sortTightB * 8)} bits, because it logs overwritten *values*, not the one bit of *why*.`);
line();
line('### Memory against the time to go back (sort, whole run)');
line();
line('| strategy | memory held after the run | to go back 1 step | to seek to an arbitrary earlier time (mean / worst) |');
line('|---|---|---|---|');
line(`| naive diary (reversible program) | ${f0(sort.historyNaive)} B | 1 undo step | ${f0(sort.revSteps / 2)} / ${f0(sort.revSteps)} undo steps |`);
line(`| tight diary (conventional twin) | ${f0(sortTightB)} B | 1 undo step | ${f0(SEED.steps / 2)} / ${f0(SEED.steps)} undo steps |`);
const sortCheckpointRows: { everySteps: number; bytes: number; snapshots: number; meanReplaySteps: number; worstReplaySteps: number }[] = [];
for (const K of SORT_KS) {
  const cp = sort.checkpoints.get(K)!;
  const sc = seekCost(sort.conv, cp);
  sortCheckpointRows.push({ everySteps: K, bytes: cp.bytes(SEED.writtenWords), snapshots: cp.snaps.length, meanReplaySteps: sc.mean, worstReplaySteps: sc.worst });
  line(`| checkpoint every ${f0(K)} steps | ${f0(cp.bytes(SEED.writtenWords))} B (${cp.snaps.length} snapshots x ${f0((16 + 1 + SEED.writtenWords) * 4)} B) | up to ${f0(K - 1)} steps of replay | ${f0(sc.mean)} / ${f0(sc.worst)} steps of replay |`);
}
const sortGarbageBytes = sort.garbageFlags * 4;
line(`| **reversible** | **${f0(sortGarbageBytes)} B** (${sort.garbageFlags} flag words; 0 B in the machine) | 1 inverse step | ${f0(sort.revSteps / 2)} / ${f0(sort.revSteps)} inverse steps |`);
line();
line('The sort is short (about 100 steps), so every number here is small and a snapshot is a large part of the whole run. One sort, one input.');
line();

// ---- pong ----
const FRAMES = 200;
const KS = [100, 1000, 10000];
const pong = await runPong(FRAMES, 'chase', KS);
if (pong.mismatches.length) throw new Error(`pong twin differs from pong.s on frames ${pong.mismatches.join(',')}`);
const PS = pong.conv.stats;
const pongTight = pong.conv.stack.byteSize;
const per = (x: number): string => f1(x / pong.frames);
const nEvents = pong.events;
line(`## Pong (${pong.frames} frames, a paddle that chases the ball, ${nEvents} key events, ${pong.hits} hits)`);
line();
line('| | reversible | conventional twin |');
line('|---|---|---|');
line(`| instructions per frame | ${f0(pong.revSteps / pong.frames)} | ${f0(PS.steps / pong.frames)} |`);
line(`| code size (instructions) | ${pong.revCodeLength} | ${pong.convCodeLength} |`);
line(`| overwriting steps per frame | 0 | ${per(PS.destroyingSteps)} |`);
line(`| **bits erased** per frame (worst case) | 0 | ${per(PS.bitsErased)} |`);
line(`| program garbage | ${f0(pong.revGarbageWords * 4)} B (its input log, ${f1((pong.revGarbageWords * 4) / pong.frames)} B/frame) | 0 |`);
line(`| input tape the replay needs | the log above | ${f0(nEvents * 8)} B (${nEvents} events x 8 B) |`);
line(`| naive diary (logging VM, 48 B/step) | ${f0(pong.historyNaive)} B (${f0(pong.historyNaive / pong.frames)} B/frame) | n/a |`);
line(`| full-width diary | n/a | ${f0(PS.bitsErased / 8)} B (${f0(PS.bitsErased / 8 / pong.frames)} B/frame) |`);
line(`| **tight diary** (real, rewinds exactly) | n/a | **${f0(pongTight)} B** (${f0(pongTight / pong.frames)} B/frame) |`);
line(`| machine history, reversible engine | **0 B** | n/a |`);
line();
line(`Step overhead of reversibility on this program: **${f1(pong.revSteps / PS.steps)}x** instructions, ${f1(pong.revCodeLength / pong.convCodeLength)}x code.`);
line();
line('### Memory against the time to go back (Pong, whole run)');
line();
line('"Undo steps" is how many instructions it takes to move back to an earlier moment, in each machine\'s own steps.');
line(`Going back one frame costs ${f0(pong.revSteps / pong.frames)} inverse steps on the reversible machine and ${f0(PS.steps / pong.frames)} undo steps on the diary.`);
line();
line('| strategy | memory held after the run | to go back 1 step | to seek to an arbitrary earlier time (mean / worst) |');
line('|---|---|---|---|');
line(`| naive diary (reversible program) | ${f0(pong.historyNaive)} B | 1 undo step | ${f0(pong.revSteps / 2)} / ${f0(pong.revSteps)} undo steps |`);
line(`| tight diary (conventional twin) | ${f0(pongTight)} B | 1 undo step | ${f0(PS.steps / 2)} / ${f0(PS.steps)} undo steps |`);
const checkpointRows: { everySteps: number; bytes: number; snapshots: number; meanReplaySteps: number; worstReplaySteps: number }[] = [];
for (const K of KS) {
  const cp = pong.checkpoints.get(K)!;
  const sc = seekCost(pong.conv, cp);
  checkpointRows.push({ everySteps: K, bytes: cp.bytes(PS.writtenWords), snapshots: cp.snaps.length, meanReplaySteps: sc.mean, worstReplaySteps: sc.worst });
  line(`| checkpoint every ${f0(K)} steps | ${f0(cp.bytes(PS.writtenWords))} B (${cp.snaps.length} snapshots x ${f0((16 + 1 + PS.writtenWords) * 4)} B) | up to ${f0(K - 1)} steps of replay | ${f0(sc.mean)} / ${f0(sc.worst)} steps of replay |`);
}
line(`| **reversible** | **${f0(pong.revGarbageWords * 4)} B** (its log; 0 B in the machine) | 1 inverse step | ${f0(pong.revSteps / 2)} / ${f0(pong.revSteps)} inverse steps |`);
line();
const cp10k = pong.checkpoints.get(10000)!;
const perFrame = (x: number): string => f1(x / pong.frames);
line('How the memory grows with the length of the run (bytes per frame, from this run):');
line(`naive diary ${perFrame(pong.historyNaive)}, tight diary ${perFrame(pongTight)}, checkpoints every 10,000 steps ${perFrame(cp10k.bytes(PS.writtenWords))},`);
line(`reversible ${perFrame(pong.revGarbageWords * 4)} (its input log; the conventional rows also need an input tape of ${f1((nEvents * 8) / pong.frames)} B/frame here).`);
line();
line('What this table says:');
line('- Against both diaries the reversible program wins on memory by a wide margin, and the machine itself needs no history.');
line('- **Checkpoint-and-replay is a serious competitor, not a straw man.** With a snapshot every 10,000 steps it holds about as');
line('  much as the reversible program log does, and it seeks to a far-away time in at most K steps, where reversible and diary');
line('  both walk one step per step. Pong has a tiny writable state (a few hundred words); a program with a large state pays that');
line('  per snapshot, while the reversible machine does not. We did not measure such a program.');
line('- What reversible does that checkpointing does not: stepping back *one* instruction costs one inverse step (a checkpoint');
line('  scheme replays up to K-1), and nothing is lost between snapshots. It pays for that with the extra instructions above.');
line();
line('## Reading this honestly');
line('- The reversible engine holds **no history**, the program keeps only its input log (Pong) or at most 19 bits (sort), and in');
line(`  exchange it runs **${f1(pong.revSteps / PS.steps)}x (Pong) and ${f1(sort.revSteps / SEED.steps)}x (sort)** more instructions than the twin. That overhead is the price, and it is real.`);
line('- Against the **naive** diary the saving is enormous. Against the **tight** diary it is large but not astronomical: Pong');
line(`  needs ${f0(pongTight)} B over ${pong.frames} frames. Against checkpointing the memory is comparable on this program. Quote the tight diary and`);
line('  the checkpoint rows as the headline comparison, not the naive one.');
line('- The tight diary is the best simple design we know. Compressing diaries (delta coding, entropy coding) could shrink it further;');
line('  we did not build one. Treat "tight" as a strong baseline, not a proven floor.');
line('- Instruction counts are for our two toy machines. Wall-clock speed is in `bench/RESULTS.md` (the reversible engine rewinds 2 to 5 times');
line('  slower per step than the logging engine).');
line('- The twins draw with XOR so the pictures match pixel for pixel, which a conventional programmer would not need to do; plain stores');
line('  would be slightly shorter. The conventional machine has no call/return, so helper code is inlined.');
line('- One game, one sort, one input pattern. Do not extrapolate.');

writeFileSync(new URL('../../TWINS.md', import.meta.url), out.join('\n') + '\n');

