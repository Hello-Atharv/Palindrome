// Line parser: labels, a mnemonic or directive, and comma-separated operands.

import type { Diagnostic } from './diag.js';

export interface Stmt {
  line: number;
  labels: string[];
  /** Lower-cased mnemonic or directive (directives start with "."), or null for label-only lines. */
  op: string | null;
  operands: string[];
  text: string;
}

const LABEL = /^\s*([A-Za-z_.$][\w.$]*)\s*:/;

/** Split on commas that are not inside [] or () or a character or string literal. */
function splitOperands(s: string): string[] {
  const out: string[] = [];
  let depth = 0;
  let inChar = false;
  let inStr = false;
  let cur = '';
  for (let k = 0; k < s.length; k++) {
    const c = s[k];
    if (c === "'" && !inStr && s[k - 1] !== '\\') inChar = !inChar;
    if (c === '"' && !inChar && s[k - 1] !== '\\') inStr = !inStr;
    if (!inChar && !inStr) {
      if (c === '[' || c === '(') depth++;
      if (c === ']' || c === ')') depth--;
      if (c === ',' && depth === 0) {
        out.push(cur.trim());
        cur = '';
        continue;
      }
    }
    cur += c;
  }
  out.push(cur.trim());
  return out;
}

function stripComment(s: string): string {
  let inChar = false;
  let inStr = false;
  for (let k = 0; k < s.length; k++) {
    if (s[k] === "'" && !inStr && s[k - 1] !== '\\') inChar = !inChar;
    if (s[k] === '"' && !inChar && s[k - 1] !== '\\') inStr = !inStr;
    if (s[k] === ';' && !inChar && !inStr) return s.slice(0, k);
  }
  return s;
}

export function parse(source: string): { stmts: Stmt[]; diagnostics: Diagnostic[] } {
  const stmts: Stmt[] = [];
  const diagnostics: Diagnostic[] = [];
  const lines = source.split(/\r?\n/);
  for (let n = 0; n < lines.length; n++) {
    let rest = stripComment(lines[n]);
    const labels: string[] = [];
    for (;;) {
      const m = LABEL.exec(rest);
      if (!m) break;
      if (m[1][0] === '$') {
        diagnostics.push({ severity: 'error', line: n + 1, message: `label "${m[1]}" is reserved (labels starting with $ are generated by macros)` });
      }
      labels.push(m[1]);
      rest = rest.slice(m[0].length);
    }
    rest = rest.trim();
    if (rest === '' && labels.length === 0) continue;
    if (rest === '') {
      stmts.push({ line: n + 1, labels, op: null, operands: [], text: lines[n].trim() });
      continue;
    }
    const m = /^(\S+)\s*(.*)$/.exec(rest)!;
    const operands = m[2] === '' ? [] : splitOperands(m[2]);
    if (operands.some((o) => o === '')) {
      diagnostics.push({ severity: 'error', line: n + 1, message: 'empty operand' });
      continue;
    }
    stmts.push({ line: n + 1, labels, op: m[1].toLowerCase(), operands, text: lines[n].trim() });
  }
  return { stmts, diagnostics };
}
